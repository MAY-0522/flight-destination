'use strict'

const fs = require('fs')
const path = require('path')
const root = __dirname

function routeFolders(parent) {
  if (!fs.existsSync(parent)) return []
  return fs.readdirSync(parent)
    .map(name => path.join(parent, name))
    .filter(folder => fs.statSync(folder).isDirectory() && fs.existsSync(path.join(folder, 'observations.json')))
}

function buildSection(folders) {
  return folders.map(folder => {
    const observationsPath = path.join(folder, 'observations.json')
    const rows = JSON.parse(fs.readFileSync(observationsPath, 'utf8'))
    if (!Array.isArray(rows)) throw new Error(`${observationsPath} must contain an array`)
    fs.writeFileSync(path.join(folder, 'observations-data.js'), `module.exports = ${JSON.stringify(rows, null, 2)}\n`)
    const destination = path.basename(folder).toUpperCase() === 'KUL-PEN' ? 'PEN' : path.basename(folder).toUpperCase()
    const relativeModule = `./${path.relative(root, folder).replace(/\\/g, '/')}/observations-data.js`
    return { destination, relativeModule }
  }).sort((a, b) => a.destination.localeCompare(b.destination))
}

const oneWayFolders = [path.join(root, 'kul-pen'), ...routeFolders(path.join(root, 'routes'))]
const roundTripFolders = routeFolders(path.join(root, 'round-trips', 'routes'))
const oneWay = buildSection(oneWayFolders)
const roundTrip = buildSection(roundTripFolders)
const sectionText = entries => entries.map(entry => `    ${JSON.stringify(entry.destination)}: require(${JSON.stringify(entry.relativeModule)})`).join(',\n')
const output = [
  '// Generated by build-observation-index.js; static JS modules are supported by WeChat Mini Program bundling.',
  'module.exports = {',
  '  oneWay: {', sectionText(oneWay),
  '  },',
  '  roundTrip: {', sectionText(roundTrip),
  '  }',
  '}',
  ''
].join('\n')
fs.writeFileSync(path.join(root, 'observation-index.js'), output)
console.log(`Generated observation modules for ${oneWay.length} one-way and ${roundTrip.length} round-trip routes.`)
